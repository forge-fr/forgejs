import type { GeneratedFileEntry } from '../types.js';
import { pkgSpec, type ResolvedGeneratorContext } from './shared.js';

export function renderControllerTemplate(ctx: ResolvedGeneratorContext): GeneratedFileEntry {
  const {
    entityPascal,
    modulePascal,
    filePrefix,
    relativeDir,
    routePath,
    crud,
    includeSchema,
    includeRepository,
  } = ctx;

  if (!crud || !includeSchema || !includeRepository) {
    const lines = [
      `import type { ForgeHttpApp } from '${pkgSpec('http')}';`,
      `import { ${modulePascal}ServiceToken } from './${filePrefix}.service.js';`,
      ``,
      `export function register${modulePascal}Controller(app: ForgeHttpApp): void {`,
      `  app.group('${routePath}', (group) => {`,
      `    group.get('/', (ctx) => {`,
      `      const service = ctx.resolve(${modulePascal}ServiceToken);`,
      `      return ctx.json(service.status());`,
      `    });`,
      `  });`,
      `}`,
      ``,
    ];
    return {
      relativePath: `${relativeDir}/${filePrefix}.controller.ts`,
      content: lines.join('\n'),
    };
  }

  const lines: string[] = [
    `import type { ForgeHttpApp } from '${pkgSpec('http')}';`,
    `import { validatedHandler } from '${pkgSpec('validation')}';`,
    `import {`,
    `  Create${entityPascal}Schema,`,
    `  ${entityPascal}IdParamsSchema,`,
    `  Update${entityPascal}Schema,`,
    `} from './${filePrefix}.schema.js';`,
    `import { ${modulePascal}ServiceToken } from './${filePrefix}.service.js';`,
    ``,
    `export function register${modulePascal}Controller(app: ForgeHttpApp): void {`,
    `  app.group('${routePath}', (group) => {`,
    `    group.get('/', async (ctx) => {`,
    `      const service = ctx.resolve(${modulePascal}ServiceToken);`,
    `      const items = await service.list();`,
    `      return ctx.json({ data: items });`,
    `    });`,
    ``,
    `    group.get('/status', (ctx) => {`,
    `      const service = ctx.resolve(${modulePascal}ServiceToken);`,
    `      return ctx.json(service.status());`,
    `    });`,
    ``,
    `    group.get(`,
    `      '/:id',`,
    `      validatedHandler(`,
    `        { params: ${entityPascal}IdParamsSchema },`,
    `        async (ctx, { params }) => {`,
    `          const service = ctx.resolve(${modulePascal}ServiceToken);`,
    `          const item = await service.getById(params.id);`,
    `          return ctx.json({ data: item });`,
    `        },`,
    `      ),`,
    `    );`,
    ``,
    `    group.post(`,
    `      '/',`,
    `      validatedHandler(`,
    `        { body: Create${entityPascal}Schema },`,
    `        async (ctx, { body }) => {`,
    `          const service = ctx.resolve(${modulePascal}ServiceToken);`,
    `          const created = await service.create(body);`,
    `          return ctx.status(201).json({ data: created });`,
    `        },`,
    `      ),`,
    `    );`,
    ``,
    `    group.patch(`,
    `      '/:id',`,
    `      validatedHandler(`,
    `        { params: ${entityPascal}IdParamsSchema, body: Update${entityPascal}Schema },`,
    `        async (ctx, { params, body }) => {`,
    `          const service = ctx.resolve(${modulePascal}ServiceToken);`,
    `          const updated = await service.update(params.id, body);`,
    `          return ctx.json({ data: updated });`,
    `        },`,
    `      ),`,
    `    );`,
    ``,
    `    group.delete(`,
    `      '/:id',`,
    `      validatedHandler(`,
    `        { params: ${entityPascal}IdParamsSchema },`,
    `        async (ctx, { params }) => {`,
    `          const service = ctx.resolve(${modulePascal}ServiceToken);`,
    `          await service.remove(params.id);`,
    `          return ctx.empty(204);`,
    `        },`,
    `      ),`,
    `    );`,
    `  });`,
    `}`,
    ``,
  ];

  return {
    relativePath: `${relativeDir}/${filePrefix}.controller.ts`,
    content: lines.join('\n'),
  };
}
